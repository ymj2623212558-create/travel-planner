# 反向：英文名 → 中文名（用于显示）
CITY_EN_TO_ZH = {v: k for k, v in CITY_ZH_TO_EN.items()}

def zh_to_en(city_zh: str) -> str:
    """中文城市名 → 英文名（用于搜索）"""
    if not city_zh:
        return ""
    city = city_zh.strip()
    return CITY_ZH_TO_EN.get(city, "")

def en_to_zh(city_en: str) -> str:
    """英文城市名 → 中文名（用于显示）"""
    if not city_en:
        return ""
    city = city_en.strip()
    return CITY_EN_TO_ZH.get(city, "")

def search_with_translation(query: str, search_fn, **kwargs):
    """智能搜索：先直接搜，若空且查询含中文则翻译后重试"""
    results = search_fn(query, **kwargs)
    if results:
        return results
    # 尝试中文翻译
    en_name = zh_to_en(query)
    if en_name:
        results = search_fn(en_name, **kwargs)
        if results:
            # 补充中文名显示
            for r in results:
                r["zh_name"] = query
    return results
